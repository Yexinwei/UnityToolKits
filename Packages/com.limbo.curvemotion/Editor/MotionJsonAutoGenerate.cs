using System;
using System.IO;
using Limbo.CurveMotion.Editor.Export;
using UnityEditor;
using UnityEngine;

namespace Limbo.CurveMotion.Editor
{
    /// <summary>
    /// 工程 Assets 下的 &lt;名字&gt;.motion.json 导入或修改时，自动在同目录生成 DOTween 代码（类名.cs）和事件处理文件（类名.Events.cs）。
    /// 生成结果和窗口“导出 C#…”完全一样，AI 或人只需要放 JSON、写调用代码、填事件方法。
    /// 规则见包里的 Documentation~/AI-GUIDE.md（菜单 Tools/Curve Motion/Copy AI Guide To Project 复制到工程根目录）。
    /// </summary>
    sealed class MotionJsonAutoGenerate : AssetPostprocessor
    {
        const string AutoGeneratedMark = "// <auto-generated>";
        const string GuideFile = "CurveMotion-AI-Guide.md";

        static void OnPostprocessAllAssets(string[] imported, string[] deleted, string[] moved, string[] movedFrom)
        {
            foreach (var path in imported)
                if (IsProjectMotionJson(path)) Generate(path);
            foreach (var path in moved)
                if (IsProjectMotionJson(path)) Generate(path);
        }

        static bool IsProjectMotionJson(string assetPath) =>
            assetPath.StartsWith("Assets/", StringComparison.Ordinal) && MotionJsonCodeGen.IsMotionJson(assetPath);

        [MenuItem("Tools/Curve Motion/Regenerate Code From .motion.json", priority = 40)]
        static void RegenerateAll()
        {
            int count = 0;
            foreach (var guid in AssetDatabase.FindAssets("t:TextAsset", new[] { "Assets" }))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                if (!IsProjectMotionJson(path)) continue;
                Generate(path);
                count++;
            }
            Debug.Log($"[Curve Motion] 重新生成了 {count} 个 .motion.json 的代码");
        }

        [MenuItem("Tools/Curve Motion/Copy AI Guide To Project", priority = 41)]
        static void CopyGuide()
        {
            var package = UnityEditor.PackageManager.PackageInfo.FindForAssembly(typeof(MotionJsonAutoGenerate).Assembly);
            string source = package != null ? Path.Combine(package.resolvedPath, "Documentation~", "AI-GUIDE.md") : null;
            if (source == null || !File.Exists(source))
            {
                EditorUtility.DisplayDialog("没找到规则文件", "包里的 Documentation~/AI-GUIDE.md 不存在，请更新 Curve Motion 包。", "确定");
                return;
            }
            string projectRoot = Path.GetDirectoryName(Application.dataPath);
            string target = Path.Combine(projectRoot, GuideFile);
            File.Copy(source, target, true);
            string line = $"动效（Curve Motion）相关的工作，先读工程根目录的 {GuideFile}，按里面的规则做。";
            EditorGUIUtility.systemCopyBuffer = line;
            EditorUtility.DisplayDialog("已复制 AI 规则文件",
                $"已复制到工程根目录：{GuideFile}\n\n" +
                "在 CLAUDE.md、AGENTS.md 或 Cursor 规则里加上下面这句（已复制到剪贴板）：\n\n" + line, "确定");
            EditorUtility.RevealInFinder(target);
        }

        /// <summary>生成一个 JSON 对应的代码。失败时打日志，不动已有文件。</summary>
        static void Generate(string jsonAssetPath)
        {
            var json = AssetDatabase.LoadAssetAtPath<TextAsset>(jsonAssetPath);
            string fullPath = Path.GetFullPath(jsonAssetPath);
            string text;
            try { text = File.ReadAllText(fullPath); }
            catch (IOException e)
            {
                Debug.LogError($"[Curve Motion] 读不了 {jsonAssetPath}：{e.Message}", json);
                return;
            }

            MotionJsonCodeGen.Result r;
            try { r = MotionJsonCodeGen.Generate(text, jsonAssetPath); }
            catch (FormatException e)
            {
                Debug.LogError($"[Curve Motion] {jsonAssetPath} 不是有效的动效 JSON，没有生成代码：{e.Message}", json);
                return;
            }

            if (!DotweenExportActions.HasDotween)
            {
                Debug.LogError($"[Curve Motion] 工程里没有 DOTween，{jsonAssetPath} 没有生成代码。装好 DOTween 后用菜单 Tools/Curve Motion/Regenerate Code From .motion.json 重新生成。", json);
                return;
            }

            string dir = Path.GetDirectoryName(jsonAssetPath).Replace('\\', '/');
            string csPath = dir + "/" + r.className + ".cs";
            string duplicate = FindOtherScript(r.className, csPath);
            if (duplicate != null)
            {
                Debug.LogError($"[Curve Motion] 已经有 {duplicate}，再生成 {csPath} 会重复定义 {r.className}，没有生成。删掉旧的，或在 JSON 的 export.className 里换个类名。", json);
                return;
            }
            if (File.Exists(csPath) && !File.ReadAllText(csPath).StartsWith(AutoGeneratedMark, StringComparison.Ordinal))
            {
                Debug.LogError($"[Curve Motion] {csPath} 已存在且不是生成的代码，没有覆盖。换个类名（export.className）或先挪走这个文件。", json);
                return;
            }

            bool changed = !File.Exists(csPath) || File.ReadAllText(csPath) != r.code;
            if (changed) File.WriteAllText(csPath, r.code);
            string eventsPath = r.data.events.Count > 0 ? DotweenExportActions.WriteEventStubs(r.data, csPath, r.className, r.ns, r.warnings) : null;
            DotweenExportActions.RememberExportedClass(r.data, (r.ns.Length > 0 ? r.ns + "." : "") + r.className);

            if (eventsPath != null) AssetDatabase.ImportAsset(eventsPath.Replace('\\', '/'));
            if (changed)
            {
                AssetDatabase.ImportAsset(csPath);
                Debug.Log($"[Curve Motion] 已由 {Path.GetFileName(jsonAssetPath)} 生成 {csPath}" + (eventsPath != null ? $"，事件写在 {Path.GetFileName(eventsPath)}" : ""), json);
            }
            if (r.warnings.Count > 0)
                Debug.LogWarning($"[Curve Motion] {jsonAssetPath} 生成代码时的警告：\n" + string.Join("\n", r.warnings), json);
        }

        /// <summary>工程里另一个同名脚本（会重复定义同一个类），没有返回 null。</summary>
        static string FindOtherScript(string className, string csPath)
        {
            foreach (var guid in AssetDatabase.FindAssets(className + " t:MonoScript"))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                if (Path.GetFileNameWithoutExtension(path) == className && path != csPath) return path;
            }
            return null;
        }
    }
}
