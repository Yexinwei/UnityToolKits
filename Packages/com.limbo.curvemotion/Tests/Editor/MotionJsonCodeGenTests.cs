using System;
using Limbo.CurveMotion.Editor.Export;
using Limbo.CurveMotion.Serialization;
using NUnit.Framework;
using UnityEngine;

namespace Limbo.CurveMotion.Editor.Tests
{
    public class MotionJsonCodeGenTests
    {
        static MotionData Line()
        {
            var data = new MotionData { name = "whatever", target = TargetKind.RectTransform };
            data.AddPoint(Vector3.zero, PointType.Corner).id = "p0";
            data.AddPoint(new Vector3(100f, 0f, 0f), PointType.Corner).id = "p1";
            return data;
        }

        [TestCase("Assets/Fx/coin-fly.motion.json", true)]
        [TestCase("Assets/Fx/CoinFly.Motion.JSON", true)]
        [TestCase("Assets/Fx/coin-fly.json", false)]
        [TestCase("Assets/Fx/motion.json", false)]
        public void IsMotionJson(string path, bool expected)
        {
            Assert.AreEqual(expected, MotionJsonCodeGen.IsMotionJson(path));
        }

        [Test]
        public void ClassNameFromFileName_GlobalNamespace()
        {
            var r = MotionJsonCodeGen.Generate(MotionJson.ToJson(Line()), "Assets/Fx/coin-fly.motion.json");
            Assert.AreEqual("CoinFlyMotion", r.className);
            Assert.AreEqual("", r.ns);
            StringAssert.Contains("public static class CoinFlyMotion", r.code);
            StringAssert.DoesNotContain("namespace ", r.code);
            StringAssert.Contains("根据同目录的 coin-fly.motion.json 自动生成", r.code);
            Assert.IsTrue(r.code.StartsWith("// <auto-generated>", StringComparison.Ordinal));
        }

        [Test]
        public void ExportBlock_RoundTripsAndOverrides()
        {
            string json = MotionJson.ToJson(Line(), "Game.Fx", "CoinFly");
            MotionJson.ReadExport(json, out string ns, out string cls);
            Assert.AreEqual("Game.Fx", ns);
            Assert.AreEqual("CoinFly", cls);
            Assert.AreEqual(2, MotionJson.FromJson(json).points.Count);

            var r = MotionJsonCodeGen.Generate(json, "Assets/Fx/coin-fly.motion.json");
            Assert.AreEqual("CoinFly", r.className);
            Assert.AreEqual("Game.Fx", r.ns);
            StringAssert.Contains("namespace Game.Fx", r.code);
            StringAssert.Contains("public static class CoinFly\n", r.code);
        }

        [Test]
        public void NoExportBlock_ReadsNull()
        {
            MotionJson.ReadExport(MotionJson.ToJson(Line()), out string ns, out string cls);
            Assert.IsNull(ns);
            Assert.IsNull(cls);
            StringAssert.DoesNotContain("\"export\": {", MotionJson.ToJson(Line()));
        }

        [Test]
        public void InvalidExportSettings_FallBackWithWarnings()
        {
            var r = MotionJsonCodeGen.Generate(MotionJson.ToJson(Line(), "Game..Fx", "class"), "Assets/coin-fly.motion.json");
            Assert.AreEqual("", r.ns);
            Assert.AreEqual("CoinFlyMotion", r.className);
            Assert.AreEqual(2, r.warnings.Count);
            // 警告写进文件头，读代码的人和 AI 能看到。
            int header = r.code.IndexOf("// </auto-generated>", StringComparison.Ordinal);
            int warning = r.code.IndexOf("// 导出警告：", StringComparison.Ordinal);
            Assert.That(warning, Is.GreaterThan(0).And.LessThan(header));
        }

        [Test]
        public void BrokenJson_Throws()
        {
            Assert.Throws<FormatException>(() => MotionJsonCodeGen.Generate("{ \"name\": ", "Assets/a.motion.json"));
        }
    }
}
